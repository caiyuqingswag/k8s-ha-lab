#!/bin/bash
set -e

########################################
# 人工确认：是否已执行 dnf update
########################################
echo "================================================="
echo "【重要确认】在继续之前请确认以下事项："
echo
echo "你是否已经手动执行过："
echo "  dnf -y update"
echo
echo "如果更新过程中升级了内核，是否已经【重启过系统】？"
echo
echo "当前正在运行的内核版本是："
echo "  $(uname -r)"
echo
echo "如果已经确认以上操作【全部完成】，请输入 yes 继续执行。"
echo "输入其他任何内容将直接退出脚本。"
echo "================================================="
read -r CONFIRM

if [ "$CONFIRM" != "yes" ]; then
  echo
  echo "已取消执行。"
  echo "请先手动执行："
  echo "  dnf -y update"
  echo "如内核有升级，请务必重启系统后再运行本脚本。"
  exit 1
fi

########################################
# 正式执行安装流程
########################################
chmod +x ./*.sh

./00-env.sh
./01-os-init.sh
./02-containerd.sh
./03-kubernetes.sh

echo "================================================="
echo " Rocky Linux 9 Kubernetes 节点初始化完成"
echo "================================================="
